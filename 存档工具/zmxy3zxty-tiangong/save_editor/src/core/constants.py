def normalize_quality(q):
    """将品质字符串归一化为标准带空格格式。

    - 已是带空格格式（如 "普 通"）原样返回；
    - 无空格且能在映射表中找到（如 "普通"）→ 返回 "普 通"；
    - 其它（占位符/未知品质）原样返回。
    """
    if not q:
        return q
    q = q.strip()
    if " " in q:
        return q
    return QUALITY_SPACE_MAP.get(q, q)


